/**
 * The lock that the CLI and the scripts share with the dashboard's
 * gatekeeper, put to the test where it serves: `sitesolide deploy`, `remove`,
 * bin/deploy-caddy.sh and bin/lock.sh, really run in front of a simulated VM
 * whose fake ssh executes the lock's scripts on its own tree.
 *
 * For each gesture: taken before the reading that decides, given back on every
 * path (success, failure, interruption), refused when the gatekeeper holds it,
 * taken over when it is stale, and handed over without being taken again to
 * the scripts run under it. The decisions themselves are tried in
 * cli-caddy-lock.test.ts.
 *
 * No test touches the machine that serves the clients: the fake ssh only
 * accepts the tests' host, the accepted writes are never executed, and the
 * CLI's zone is a name that does not resolve.
 */

const TEMP_DIRS: string[] = [];
let vm: FakeVm;

function tempDir(prefix: string): string {
  const folder = realpathSync(mkdtempSync(join(tmpdir(), prefix)));
  TEMP_DIRS.push(folder);
  return folder;
}

afterEach(() => {
  vm?.resume();
  vm?.cleanup();
  for (const folder of TEMP_DIRS.splice(0)) rmSync(folder, { recursive: true, force: true });
});

function text(manifest: Manifest): string {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

function project(manifest: Manifest, build?: string): string {
  const folder = tempDir("project-lock-");
  writeFileSync(join(folder, "sitesolide.json"), text(build === undefined ? manifest : { ...manifest, build }));
  mkdirSync(join(folder, "public"));
  writeFileSync(join(folder, "public", "index.html"), "<p>test</p>\n");
  return folder;
}

/** A HOME whose configuration aims at a zone that does not resolve: the final check reaches nobody. */
function offlineHome(): Record<string, string> {
  const home = tempDir("home-lock-");
  mkdirSync(join(home, ".config", "sitesolide"), { recursive: true });
  writeFileSync(
    join(home, ".config", "sitesolide", "config.json"),
    // A complete configuration, minus the server, which vm.env lays down: the
    // CLI refuses to guess a machine, and a missing setting would make the
    // test fail on that refusal rather than on what it measures.
    JSON.stringify({ zone: TEST_ZONE, email: TEST_EMAIL }),
  );
  return { HOME: home };
}

/**
 * A test repository: the Caddyfile, the blocks generated by the test in
 * `blocks/`, and links to the real scripts, which deduce the root from their
 * own path. bin/deploy-caddy.sh receives those blocks as arguments, as
 * `sitesolide deploy` hands it the one it generates.
 */
function testRepo(blocks: Manifest[]): string {
  const repo = tempDir("repo-lock-");
  mkdirSync(join(repo, "bin"));
  copyFileSync(join(REPO, "bin", "sitesolide.ts"), join(repo, "bin", "sitesolide.ts"));
  for (const name of ["cli", "config.sh", "deploy-caddy.sh", "portal-guard.ts", "lock.sh", "generate-domains.sh", "deploy-gatekeeper.sh"]) {
    symlinkSync(join(REPO, "bin", name), join(repo, "bin", name));
  }
  mkdirSync(join(repo, "infra", "caddy"), { recursive: true });
  writeFileSync(join(repo, "infra", "caddy", "Caddyfile"), CADDYFILE);
  mkdirSync(join(repo, "blocks"));
  for (const manifest of blocks) {
    writeFileSync(join(repo, "blocks", `${manifest.slug}.caddy`), generateFragment(manifest)!);
  }
  return repo;
}

const CADDYFILE = "# test Caddyfile\n";

type Outcome = { code: number; output: string; error: string };

async function waitFor(proc: Bun.Subprocess<"ignore", "pipe", "pipe">): Promise<Outcome> {
  const [output, error] = await Promise.all([
    new Response(proc.stdout).text(),
    new Response(proc.stderr).text(),
  ]);
  return { code: await proc.exited, output, error };
}

function script(repo: string, name: string, arguments_: string[], env: Record<string, string> = {}) {
  // bin/deploy-caddy.sh deposits only the blocks it is handed: the test
  // repository's, generated for it.
  const folder = join(repo, "blocks");
  const blocks =
    name === "deploy-caddy.sh" && existsSync(folder)
      ? readdirSync(folder).filter((file) => file.endsWith(".caddy")).map((file) => join(folder, file))
      : [];
  return Bun.spawn(["bash", join(repo, "bin", name), ...arguments_, ...blocks], {
    stdout: "pipe",
    stderr: "pipe",
    // The zone has no default: the script reads it in bin/config.sh, which
    // refuses to guess a machine. The test's resolves nowhere and belongs to
    // nobody.
    env: {
      SITESOLIDE_ZONE: TEST_ZONE,
      SITESOLIDE_EMAIL: TEST_EMAIL,
      ...process.env,
      ...vm.env,
      ...env,
    },
  });
}

/** Waits until the fake ssh has paused, then sends the signal to the process. */
async function interruptAtPause(pid: number, line: string, signal: "SIGTERM" | "SIGINT" = "SIGTERM"): Promise<void> {
  const deadline = Date.now() + 15_000;
  while (!vm.logs().includes(`PAUSE ${line}`)) {
    if (Date.now() > deadline) throw new Error(`no pause on ${line}: ${vm.logs().join(" | ")}`);
    await Bun.sleep(20);
  }
  process.kill(pid, signal);
  // Bash waits for the end of the command in progress before handling the
  // signal.
  await Bun.sleep(100);
  vm.resume();
}

const CMS: Manifest = { slug: "cms", port: 3048, publicDir: "public", start: "bun run server.ts", portal: true };
const TOOL: Manifest = { slug: "tool", port: 3030, publicDir: "public", start: "bun run server.ts" };

/** A VM that already carries exactly the repository's configuration: deploy-caddy.sh has nothing to do. */
function vmUpToDate(): void {
  vm.writeManifest("cms", text(CMS));
  vm.writeFile("/etc/caddy/Caddyfile", CADDYFILE);
  vm.writeBlock("cms", generateFragment(CMS)!);
}

describe("bin/deploy-caddy.sh holds the guard's lock to the end", () => {
  test("taken before the guard, given back on the path that succeeds", async () => {
    vm = createFakeVm();
    vmUpToDate();
    const r = await waitFor(script(testRepo([CMS]), "deploy-caddy.sh", []));
    expect(r.error).toBe("");
    expect(r.code).toBe(0);
    expect(r.output).toContain("nothing to do");
    expect(vm.logs()).toEqual([
      "CONNECT",
      "LOCK take deploy-caddy",
      "READ *",
      "FINGERPRINT",
      "FINGERPRINT",
      "BLOCKS",
      "LOCK release deploy-caddy",
    ]);
    expect(vm.lock()).toBeNull();
  });

  test("given back when a write fails after the guard", async () => {
    vm = createFakeVm();
    vm.writeManifest("cms", text(CMS));
    const r = await waitFor(script(testRepo([CMS]), "deploy-caddy.sh", []));
    expect(r.code).not.toBe(0);
    const logs = vm.logs();
    expect(logs.some((line) => line.startsWith("REFUSED sudo mkdir -p /var/backups/caddy/"))).toBe(true);
    expect(logs.at(-1)).toBe("LOCK release deploy-caddy");
    expect(vm.lock()).toBeNull();
  });

  test("given back on an interruption, without anything else leaving", async () => {
    vm = createFakeVm();
    vmUpToDate();
    vm.pause("READ *");
    const proc = script(testRepo([CMS]), "deploy-caddy.sh", []);
    await interruptAtPause(proc.pid, "READ *");
    const r = await waitFor(proc);
    expect(r.code).toBe(143);
    const logs = vm.logs();
    expect(logs.at(-1)).toBe("LOCK release deploy-caddy");
    expect(logs).not.toContain("FINGERPRINT");
    expect(vm.lock()).toBeNull();
  });

  test("held by the gatekeeper: refusal before the guard, and its lock stays in place", async () => {
    vm = createFakeVm();
    vmUpToDate();
    const since = Date.now() - 30_000;
    vm.setLock(`gatekeeper 4242 ${since}`);
    const r = await waitFor(script(testRepo([CMS]), "deploy-caddy.sh", []));
    expect(r.code).toBe(1);
    expect(r.error).toContain(`a portal change from the dashboard is in progress (since ${utcTime(since)}): try again in a moment`);
    expect(vm.logs()).toEqual(["CONNECT", "LOCK take deploy-caddy"]);
    expect(vm.lock()).toBe(`gatekeeper 4242 ${since}`);
  });

  test("stale for more than fifteen minutes: taken over while saying so, then given back", async () => {
    vm = createFakeVm();
    vmUpToDate();
    const since = Date.now() - 20 * 60_000;
    vm.setLock(`gatekeeper 4242 ${since}`, 20 * 60_000);
    const r = await waitFor(script(testRepo([CMS]), "deploy-caddy.sh", []));
    expect(r.code).toBe(0);
    expect(r.error).toContain(`stale Caddy lock taken over: held by gatekeeper since ${utcTime(since)}`);
    expect(vm.logs().slice(0, 4)).toEqual(["CONNECT", "LOCK take deploy-caddy", "LOCK retake deploy-caddy", "READ *"]);
    expect(vm.logs().at(-1)).toBe("LOCK release deploy-caddy");
    expect(vm.lock()).toBeNull();
  });

  test("ownership handed over: checked, neither taken again nor given back", async () => {
    vm = createFakeVm();
    vmUpToDate();
    const line = `deploy 777 ${Date.now()}`;
    vm.setLock(line);
    const r = await waitFor(script(testRepo([CMS]), "deploy-caddy.sh", [], { CADDY_LOCK_HELD: line }));
    expect(r.code).toBe(0);
    const logs = vm.logs();
    expect(logs.slice(0, 3)).toEqual(["CONNECT", "LOCK verify deploy", "READ *"]);
    expect(logs.filter((entry) => entry.startsWith("LOCK"))).toEqual(["LOCK verify deploy"]);
    // The caller still holds it: it is up to it to give it back.
    expect(vm.lock()).toBe(line);
  });

  test("ownership handed over that the VM does not confirm: refusal before the guard", async () => {
    vm = createFakeVm();
    vmUpToDate();
    vm.setLock(`gatekeeper 4242 ${Date.now()}`);
    const r = await waitFor(
      script(testRepo([CMS]), "deploy-caddy.sh", [], { CADDY_LOCK_HELD: `deploy 777 ${Date.now()}` }),
    );
    expect(r.code).toBe(1);
    expect(r.error).toContain("CADDY_LOCK_HELD says the caller holds the Caddy lock, and the server does not confirm it");
    expect(vm.logs()).toEqual(["CONNECT", "LOCK verify deploy"]);
    expect(vm.lock()).toStartWith("gatekeeper 4242 ");
  });

  test("an ownership handed over that is not a holder line never reaches the VM", async () => {
    vm = createFakeVm();
    vmUpToDate();
    const r = await waitFor(script(testRepo([CMS]), "deploy-caddy.sh", [], { CADDY_LOCK_HELD: "deploy 1 2; reboot" }));
    expect(r.code).toBe(1);
    expect(vm.logs()).toEqual(["CONNECT"]);
  });

  test("in a dry run, no lock is taken", async () => {
    vm = createFakeVm();
    vm.writeManifest("cms", text(CMS));
    const r = await waitFor(script(testRepo([CMS]), "deploy-caddy.sh", ["--dry-run"]));
    expect(r.code).toBe(0);
    expect(vm.logs().some((line) => line.startsWith("LOCK"))).toBe(false);
  });
});

