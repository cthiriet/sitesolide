describe("bin/deploy-gatekeeper.sh does not install under a transaction", () => {
  const INSTALL = "sudo install -D -m 0644 -o root -g root";
  const LIST_UNITS = "ACCEPTED systemctl list-units --all --plain --no-legend --state=activating 'sitesolide-gatekeeper*' 2>/dev/null";

  /** A repository whose dashboard builds into a trivial file: nothing from the real dashboard/ is touched. */
  function gatekeeperRepo(): string {
    const repo = testRepo([]);
    mkdirSync(join(repo, "dashboard"));
    writeFileSync(join(repo, "dashboard", "package.json"), JSON.stringify({ scripts: { borrow: "true" } }));
    writeFileSync(join(repo, "dashboard", "gatekeeper.ts"), 'console.log("test gatekeeper");\n');
    mkdirSync(join(repo, "infra", "gatekeeper"), { recursive: true });
    for (const unit of ["sitesolide-gatekeeper-on@.service", "sitesolide-gatekeeper-off@.service"]) {
      writeFileSync(join(repo, "infra", "gatekeeper", unit), "[Service]\n");
    }
    return repo;
  }

  test("taken before the check on transactions, given back once installed, before the verifications", async () => {
    // The verifications then fail, the simulated VM giving back no
    // fingerprint: the lock has already been given back.
    vm = createFakeVm();
    vm.acceptWrites();
    const r = await waitFor(script(gatekeeperRepo(), "deploy-gatekeeper.sh", []));
    expect(r.code).toBe(1);
    const logs = vm.logs();
    const taken = logs.indexOf("LOCK take deploy-gatekeeper");
    const list = logs.indexOf(LIST_UNITS);
    const install = logs.findIndex((line) => line.includes(INSTALL));
    const release = logs.indexOf("LOCK release deploy-gatekeeper");
    expect(taken).toBeGreaterThan(-1);
    expect(list).toBeGreaterThan(taken);
    expect(install).toBeGreaterThan(list);
    expect(release).toBeGreaterThan(install);
    expect(logs.findIndex((line) => line.includes("sudo sha256sum"))).toBeGreaterThan(release);
    expect(vm.lock()).toBeNull();
  });

  test("held by the gatekeeper: refusal before the check and before any install", async () => {
    vm = createFakeVm();
    vm.acceptWrites();
    const since = Date.now();
    vm.setLock(`gatekeeper 4242 ${since}`);
    const r = await waitFor(script(gatekeeperRepo(), "deploy-gatekeeper.sh", []));
    expect(r.code).toBe(1);
    expect(r.error).toContain(`a portal change from the dashboard is in progress (since ${utcTime(since)}): try again in a moment`);
    expect(vm.logs()).not.toContain(LIST_UNITS);
    expect(vm.logs().some((line) => line.includes(INSTALL))).toBe(false);
    expect(vm.lock()).toBe(`gatekeeper 4242 ${since}`);
  });

  test("a transaction in progress from a gatekeeper without a lock is still refused, and the lock given back", async () => {
    vm = createFakeVm();
    vm.acceptWrites();
    vm.answer("--state=activating", "sitesolide-gatekeeper-on@cms.service loaded activating start start\n");
    const r = await waitFor(script(gatekeeperRepo(), "deploy-gatekeeper.sh", []));
    expect(r.code).toBe(1);
    expect(r.error).toContain("a gatekeeper transaction is in progress, try again in a minute");
    expect(vm.logs().some((line) => line.includes(INSTALL))).toBe(false);
    expect(vm.logs().at(-1)).toBe("LOCK release deploy-gatekeeper");
    expect(vm.lock()).toBeNull();
  });

  test("ownership handed over: checked, neither taken again nor given back", async () => {
    vm = createFakeVm();
    vm.acceptWrites();
    const line = `deploy 777 ${Date.now()}`;
    vm.setLock(line);
    const r = await waitFor(script(gatekeeperRepo(), "deploy-gatekeeper.sh", [], { CADDY_LOCK_HELD: line }));
    expect(r.code).toBe(1);
    expect(vm.logs().filter((entry) => entry.startsWith("LOCK"))).toEqual(["LOCK verify deploy"]);
    expect(vm.lock()).toBe(line);
  });
});

/**
 * A deployment deposits its own site's block and nothing else. It used to
 * deposit every block kept on the workstation, and therefore had to stop as
 * soon as ANOTHER site's door had changed from the dashboard, since it would
 * have overwritten it. With no such copies, another site is none of its
 * business.
 */
describe("sitesolide deploy leaves the other sites' blocks alone", () => {
  const APP: Manifest = { slug: "sample-door", port: 3035, publicDir: "public", start: "bun run server.ts" };

  test("another site changed from the dashboard stops nothing, and its block is not even read", async () => {
    vm = createFakeVm();
    vm.writeManifest("tool", text({ ...TOOL, portal: true }));
    const repo = testRepo([TOOL]);
    const folder = project(APP, "touch built");
    const r = await run(folder, ["deploy", "--dry-run"], { vm, cli: join(repo, "bin", "sitesolide.ts") });
    expect(r.code).toBe(0);
    expect(r.all).not.toContain("portal of tool");
    expect(existsSync(join(folder, "built"))).toBe(true);
    // Its manifest is read with every other one, for the ports it declares;
    // its block is not.
    expect(vm.logs()).toEqual(["READ sample-door", "READ *"]);
  });

  test("the site in progress, whose door the dashboard changed, follows it", async () => {
    // Its block will follow the VM's door: see decideBlock.
    vm = createFakeVm();
    vm.writeManifest("sample-door", text({ ...APP, portal: true }));
    vm.writeManifest("tool", text(TOOL));
    const repo = testRepo([APP, TOOL]);
    const folder = project(APP, "touch built");
    const r = await run(folder, ["deploy", "--dry-run"], { vm, cli: join(repo, "bin", "sitesolide.ts") });
    expect(r.code).toBe(0);
    expect(r.output).toContain("portal was turned on from the dashboard");
    expect(existsSync(join(folder, "built"))).toBe(true);
  });

  test("a static site, which does not go through deploy-caddy.sh, reads its own door alone", async () => {
    vm = createFakeVm();
    vm.writeManifest("tool", text({ ...TOOL, portal: true }));
    const repo = testRepo([TOOL]);
    const r = await run(project({ slug: "sample-static", publicDir: "public" }), ["deploy", "--dry-run"], {
      vm,
      cli: join(repo, "bin", "sitesolide.ts"),
    });
    expect(r.code).toBe(0);
    expect(vm.logs()).toEqual(["READ sample-static"]);
  });
});

describe("sitesolide remove of a site behind the portal", () => {
  const PROTECTED: Manifest = { slug: "sample-door", port: 3035, publicDir: "public", start: "bun run server.ts", portal: true };
  const VINEYARD: Manifest = { slug: "vineyard", publicDir: "public" };

  test("the service and public/ go before the block, and the rest of the folder after", async () => {
    vm = createFakeVm();
    vm.writeManifest("sample-door", text(PROTECTED));
    const repo = testRepo([PROTECTED]);
    const r = await run(project(PROTECTED), ["remove", "--confirm", "sample-door", "--dry-run"], {
      vm,
      cli: join(repo, "bin", "sitesolide.ts"),
    });
    expect(r.code).toBe(0);
    const service = r.output.indexOf("systemctl disable --now sample-door");
    const publicDir = r.output.indexOf("rm -rf /srv/sites/sample-door/public");
    const block = r.output.indexOf("SITESOLIDE_REMOVE=sample-door.caddy");
    const folder = r.output.indexOf("rm -rf /srv/sites/sample-door\n");
    expect(service).toBeGreaterThan(-1);
    expect(publicDir).toBeGreaterThan(service);
    expect(block).toBeGreaterThan(publicDir);
    expect(folder).toBeGreaterThan(block);
  });

  test("an open site keeps the previous order: the block first", async () => {
    vm = createFakeVm();
    const open: Manifest = { ...PROTECTED, portal: undefined };
    vm.writeManifest("sample-door", text(open));
    const repo = testRepo([open]);
    const r = await run(project(open), ["remove", "--confirm", "sample-door", "--dry-run"], {
      vm,
      cli: join(repo, "bin", "sitesolide.ts"),
    });
    expect(r.code).toBe(0);
    expect(r.output).not.toContain("/srv/sites/sample-door/public");
    expect(r.output.indexOf("SITESOLIDE_REMOVE=")).toBeLessThan(r.output.indexOf("systemctl disable --now"));
  });

  test("for real: lock held from the start, public/ removed before the block, ownership handed over, given back on the failure", async () => {
    // A showcase closed from the dashboard, whose block only exists on the VM.
    // deploy-caddy.sh goes as far as the validation, which the simulated VM
    // does not confirm: it restores, fails, and the removal stops there.
    vm = createFakeVm();
    vm.writeManifest("vineyard", text({ ...VINEYARD, portal: true }));
    vm.writeBlock("vineyard", "# set by the gatekeeper\n");
    vm.acceptWrites();
    const repo = testRepo([CMS]);
    const r = await run(project(VINEYARD), ["remove", "--confirm", "vineyard"], {
      vm,
      cli: join(repo, "bin", "sitesolide.ts"),
      env: offlineHome(),
    });
    expect(r.code).toBe(1);
    expect(r.error).toContain("configuration refused by caddy validate");
    const logs = vm.logs();
    const lockLines = logs.filter((line) => line.startsWith("LOCK"));
    expect(lockLines).toEqual(["LOCK take deploy", "LOCK verify deploy", "LOCK release deploy"]);
    expect(logs[0]).toBe("LOCK take deploy");
    expect(logs[1]).toBe("READ vineyard");
    const publicDir = logs.indexOf("ACCEPTED sudo rm -rf /srv/sites/vineyard/public");
    expect(publicDir).toBeGreaterThan(1);
    expect(publicDir).toBeLessThan(logs.indexOf("CONNECT"));
    // The rest of the folder waits for a block that was removed, and it was
    // not.
    expect(logs).not.toContain("ACCEPTED sudo rm -rf /srv/sites/vineyard");
    expect(logs.at(-1)).toBe("LOCK release deploy");
    expect(vm.lock()).toBeNull();
  });
});
