#!/usr/bin/env bash
#
# Code lock of a preview.
#
#   bin/lock.sh enable <slug>    closes the preview, generates a code,
#                                or recalls the one in force if already closed
#   bin/lock.sh code <slug>      replaces the code by a fresh one
#   bin/lock.sh disable <slug>   reopens the preview
#   bin/lock.sh state [slug]     state of each site, measured on the VM
#
# A preview subdomain is publicly reachable: the noindex keeps it out of Google,
# it closes it to nobody. This script closes it behind a six-character code,
# which the client receives once in a link and which his browser then keeps in a
# cookie.
#
# What the gesture touches, in order:
#
#   0. the lock the scripts share with the dashboard's gatekeeper, taken before
#      the guard and released once Caddy is reloaded or restored, see
#      take_caddy_lock; then the manifest deposited on the VM is read, and
#      if it asks for a door other than the local manifest's, or the portal for
#      a lock, the gesture stops there, see require_portal_agreed;
#   1. <sites repository>/<slug>/sitesolide.json, field "lock", versioned and to
#      be committed: it is a site's only configuration file, and a lock set
#      elsewhere would be erased at the next deployment;
#   2. the same file on the VM, which the generator reads;
#   3. the file of codes on the VM, outside the repository;
#   4. the door page, if it is missing;
#   5. the Caddy fragment, deposited, validated, reloaded, and RESTORED if the
#      validation OR the reload fails.
#
# The code is never typed in nor passed as an argument: it is generated by the
# workstation, passed through the standard input of the commands that need it,
# and shown from the exit trap, hence on EVERY path. A lock in service whose
# code nobody knows is repaired by hand on the VM, and only there: it is the
# only failure of this script that has no catching up.
#
# WARNING: neither "caddy stop" nor "caddy start" here, ever. Those commands
# address the administration API of the instance in service, whatever the
# --config given, and stop production. Only systemctl reload applies a
# configuration. See the Production section of CLAUDE.md.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
. "$REPO_ROOT/bin/config.sh"
sitesolide_require_config
# The repository that carries the projects' code, if there is one:
# SITESOLIDE_SITES_REPO, set by bin/config.sh from the configuration. An
# installation that has none leaves it empty, and the lock then reads the
# current project's folder.

# Paths on the VM. The folder of locks is the one the Caddyfile imports by glob;
# the file of codes deliberately lives outside it, otherwise Caddy would try to
# import it as a configuration.
LOCKS_DIR="${LOCKS_DIR:-/etc/caddy/locks}"
CODES_FILE="${CODES_FILE:-/etc/caddy/locks-codes.json}"
DOOR_PAGES_DIR="${DOOR_PAGES_DIR:-/srv/garde}"
SITES_DIR="${SITES_DIR:-/srv/sites}"

WORK="$(mktemp -d)"

# Working folder on the VM, opened on demand. Nothing goes through /tmp directly
# any more: that folder is sticky, one only unlinks one's own files there, and a
# file deposited there by sudo belongs to root. The cleanup "rm" therefore
# failed, exited 1, and killed the script AFTER the reload, before the code was
# announced. A folder of our own, outside the sticky one, empties without asking
# itself the question.
WORK_VM=""
CODE=""
ANNOUNCED=no
CADDY_LOCK=""

open_work_vm() {
  [ -z "$WORK_VM" ] || return 0
  WORK_VM="$(ssh "$SITESOLIDE_SERVER" 'mktemp -d /tmp/lock.XXXXXXXX')"
  [ -n "$WORK_VM" ] || { echo "could not create the working folder on the VM" >&2; exit 1; }
}

# One single exit point, whatever the path. It does two things, and the second
# is the more important: it never lets a code go without having said it. See
# announce().
on_exit() {
  local status=$?
  rm -rf "$WORK"
  if [ -n "$WORK_VM" ]; then
    # The folder belongs to us, but it contains copies made by sudo.
    ssh "$SITESOLIDE_SERVER" "sudo rm -rf $WORK_VM" >/dev/null 2>&1 || true
  fi
  release_caddy_lock
  if [ -n "$CODE" ] && [ "$ANNOUNCED" = no ]; then
    announce "$CODE" "$status"
  fi
  exit "$status"
}
trap on_exit EXIT
# An interruption goes through exit, hence through on_exit: the lock is
# released and the code announced on that path too.
trap 'exit 130' INT
trap 'exit 143' TERM

usage() {
  sed -n '3,9p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//' >&2
  exit 2
}

# --- reading the local state -------------------------------------------------

require_site() {
  [ -n "${SLUG:-}" ] || usage

  # The landing has no preview to lock: it lives on the bare domain, without a
  # subdomain and without a manifest, the CLI refusing its slug. Without this
  # refusal, write_lock would fail on a missing file, after having let people
  # believe that the gesture had begun.
  [ "$SLUG" = landing ] && { echo "the landing has no preview to lock" >&2; exit 1; }

  # SITESOLIDE_PROJECT_DIR is what "sitesolide lock" sets, which knows where the
  # project lives. Without it, the folder is inferred from the slug, which
  # assumes that it carries its name: true in the sites repository, false for a
  # project deployed from somewhere else.
  SITE_FOLDER="${SITESOLIDE_PROJECT_DIR:-${SITESOLIDE_SITES_REPO:-}/$SLUG}"
  [ -d "$SITE_FOLDER" ] || { echo "folder not found: $SITE_FOLDER" >&2; exit 1; }
  MANIFEST="$SITE_FOLDER/sitesolide.json"
  [ -f "$MANIFEST" ] || { echo "manifest not found: $MANIFEST" >&2; exit 1; }
  HOST="$SLUG.$SITESOLIDE_ZONE"

  local fields
  fields="$(manifest_fields "$MANIFEST")"
  { read -r LOCKED; read -r DOMAIN; read -r ACTIVE; } <<<"$fields"
}

# What the manifest says of the lock and of the final domain: "lock",
# "domain.name" and "domain.active", in that order, one value per line. A column
# separator would be a trap here, the shell's "read" merging consecutive tabs
# and shifting everything as soon as a domain is missing.
#
# The reading goes through readManifest and not through a home-made JSON.parse:
# a manifest the CLI refuses must stop the gesture here, not deploy itself
# later.
manifest_fields() {
  (cd "$REPO_ROOT" && FILE_PATH="$1" bun -e '
    import { readManifest } from "./bin/cli/manifest";

    const path = process.env.FILE_PATH;
    const file = Bun.file(path);
    let manifest;
    if (await file.exists()) {
      const read = readManifest(await file.text());
      if (read.manifest === undefined) {
        process.stderr.write(`${path} : ${read.errors.join(", ")}\n`);
        process.exit(1);
      }
      manifest = read.manifest;
    }
    const fields = [
      manifest?.lock === true,
      manifest?.domain?.name ?? "",
      manifest?.domain?.active === true,
    ];
    process.stdout.write(`${fields.join("\n")}\n`);
  ')
}

# The lock closes ONLY the preview. A site whose final domain is in service goes
# on serving the same content, without a code and indexable: closing the
# subdomain then closes nothing at all, and the "Preview closed" shown at the
# end would be a lie by omission. The gesture therefore stops, unless the
# operator explicitly refuses that.
require_preview_only() {
  [ "$ACTIVE" = "true" ] || return 0

  cat >&2 <<EOF

   STOP: $SLUG already serves its final domain.

   The lock only closes https://$HOST/.
   https://$DOMAIN/ would stay open to everyone, without a code and indexable:
   the site would not be closed, only its preview would be.

   Closing the final domain is another gesture, which does not go through here.
   To lock the preview all the same, knowingly:

     LOCK_DESPITE_DOMAIN=1 bin/lock.sh $SUBCOMMAND $SLUG

EOF
  [ "${LOCK_DESPITE_DOMAIN:-}" = "1" ] || exit 1
  echo "   LOCK_DESPITE_DOMAIN=1: the preview is closed, the domain stays open." >&2
}

# The portal of a deployed site is set from the dashboard, and the VM is the
# source of truth. This script deposits the local manifest as it is: on a site
# closed or reopened from the dashboard, it would erase the door of the
# deposited manifest, and bin/deploy-caddy.sh would then see no divergence left
# to refuse, then would serve the site in the clear on the first deposit. The
# deposited manifest is therefore read before any write, and a door that differs
# from the local manifest stops the gesture by pointing to "sitesolide deploy",
# which makes the repository catch up. A lock on a site behind the portal is
# refused too: validate() forbids them together, and it is from the dashboard
# that the door is removed.
#
# An unreadable read stops the gesture. See bin/portal-guard.ts, and
# bin/cli/portal-vm.ts for the decision.
require_portal_agreed() {
  SITESOLIDE_SERVER="$SITESOLIDE_SERVER" bun "$REPO_ROOT/bin/portal-guard.ts" --manifest "$SLUG" "$MANIFEST" "$1" || exit 1
}

# The lock this script shares with the dashboard's gatekeeper and
# bin/deploy-caddy.sh, see bin/cli/caddy-lock.ts. The gatekeeper rewrites the
# deposited manifest and the site's block, validates and reloads Caddy: without
# this lock, a portal set between the guard and the manifest deposit was erased
# by it, and the reload or the restore from here could fall in the middle of its
# transaction. Taken before the guard, released once Caddy is reloaded or
# restored, and by on_exit on every other path.
#
# Launched by `sitesolide remove`, which already holds it, the script receives
# its line in CADDY_LOCK_HELD: it checks that the VM carries it, and neither
# takes nor releases anything.
take_caddy_lock() {
  if [ -n "${CADDY_LOCK_HELD:-}" ]; then
    echo "-> Caddy lock: held by the caller ($CADDY_LOCK_HELD)"
    SITESOLIDE_SERVER="$SITESOLIDE_SERVER" bun "$REPO_ROOT/bin/portal-guard.ts" --lock verify "$CADDY_LOCK_HELD" || exit 1
    return 0
  fi
  echo "-> Caddy lock"
  CADDY_LOCK="$(SITESOLIDE_SERVER="$SITESOLIDE_SERVER" bun "$REPO_ROOT/bin/portal-guard.ts" --lock take lock $$)" || exit 1
}

release_caddy_lock() {
  [ -n "$CADDY_LOCK" ] || return 0
  SITESOLIDE_SERVER="$SITESOLIDE_SERVER" bun "$REPO_ROOT/bin/portal-guard.ts" --lock release "$CADDY_LOCK" || true
  CADDY_LOCK=""
}

# The field is written without touching the rest of the manifest: "domain",
# "env" and the other keys govern the deployment and are none of the lock's
# business.
write_lock() {
  # The manifest leaves next to the site: a folder missing on the VM means that
  # the site has never been deployed, and rsync would fail further on without
  # saying why.
  ssh "$SITESOLIDE_SERVER" "test -d $SITES_DIR/$SLUG" || {
    echo "$SLUG is not deployed: run sitesolide deploy first" >&2
    exit 1
  }

  echo "-> sitesolide.json: lock = $2"
  (cd "$REPO_ROOT" && FILE_PATH="$1" VALUE="$2" bun -e '
    import { setLock } from "./bin/cli/manifest";
    const path = process.env.FILE_PATH;
    const raw = await Bun.file(path).text();
    await Bun.write(path, setLock(raw, process.env.VALUE === "true"));
  ')

  # The manifest leaves for the exact place where "sitesolide deploy" sets it,
  # and it is the same file: without this immediate deposit, the lock generator
  # would only see the change at the next deployment.
  #
  # The mode is set before the copy, rsync -a preserving the source's: the
  # manifest is read by the generator, which does not run under our account.
  cp "$1" "$WORK/sitesolide.json"
  chmod 644 "$WORK/sitesolide.json"
  rsync -a "$WORK/sitesolide.json" "$SITESOLIDE_SERVER:$SITES_DIR/$SLUG/sitesolide.json"
}

# The fragment only has an effect if the configuration IN SERVICE imports it.
# Without this check, the omission only showed at the very end, in 200 instead
# of 401, after the code had been set and the fragment installed. It now shows
# beforehand. The machine says which block serves the site: an application
# site's own block if it has one, more specific than *.$SITESOLIDE_ZONE, the
# Caddyfile otherwise.
require_import() {
  local target=/etc/caddy/Caddyfile repair="bin/deploy-caddy.sh"
  if ssh "$SITESOLIDE_SERVER" "sudo test -f /etc/caddy/sites/$SLUG.caddy"; then
    target="/etc/caddy/sites/$SLUG.caddy"
    repair="sitesolide deploy, from the site's folder"
  fi

  ssh "$SITESOLIDE_SERVER" "sudo grep -qs 'import $LOCKS_DIR/\*.caddy' $target" || {
    cat >&2 <<EOF
STOP: $target does not import $LOCKS_DIR/*.caddy.

The lock would be generated, installed, and have no effect at all: the preview
would stay open to everyone. Put the generated version in service first:

  $repair
EOF
    exit 1
  }
}

# --- code --------------------------------------------------------------------

# The code is drawn on the workstation, by the same function the tests cover. It
# is never asked of the operator: a code chosen by hand would be guessable, and
# a code typed in would end up in the shell's history.
generate_code() {
  (cd "$REPO_ROOT/api" && bun -e '
    import { generateCode } from "./src/locks";
    process.stdout.write(generateCode());
  ')
}

# The code in force on the VM, empty if the site has none. It never comes out of
# a file of the repository: the codes live on the machine and nowhere else.
code_in_force() {
  ssh "$SITESOLIDE_SERVER" "sudo cat $CODES_FILE 2>/dev/null || echo '{}'" | SLUG="$SLUG" bun -e '
    const codes = JSON.parse((await Bun.stdin.text()).trim() || "{}");
    process.stdout.write(codes[process.env.SLUG] ?? "");
  '
}

# The file of codes is fetched, modified on the workstation, then set back. The
# code goes through an environment variable and not through an argument: an
# argument stays readable in the machine's process list.
#
# The code is set before the fragment is regenerated. A fragment that failed to
# install would therefore leave a recorded code with no effect, the old one
# going on serving: harmless, and "bin/lock.sh state" shows the gap between what
# is wanted and what is installed.
set_code() {
  local value="$1"

  ssh "$SITESOLIDE_SERVER" "sudo cat $CODES_FILE 2>/dev/null || echo '{}'" > "$WORK/codes.json"
  FILE_PATH="$WORK/codes.json" SLUG="$SLUG" LOCK_CODE="$value" bun -e '
    const path = process.env.FILE_PATH;
    const raw = (await Bun.file(path).text()).trim();
    const codes = raw === "" ? {} : JSON.parse(raw);
    const code = process.env.LOCK_CODE;
    if (code === "") delete codes[process.env.SLUG];
    else codes[process.env.SLUG] = code;
    await Bun.write(path, JSON.stringify(codes, null, 2) + "\n");
  '

  # The mode is set before the copy, not after: rsync -a preserves the source's,
  # and a 644 on the VM would expose every code in force for the time of the
  # transfer, and until the next cleanup on the failure paths.
  chmod 600 "$WORK/codes.json"
  open_work_vm
  rsync -a "$WORK/codes.json" "$SITESOLIDE_SERVER:$WORK_VM/codes.json"
  # Readable by the only account that launches the generator. The code is not a
  # cryptographic secret, it is in the clear in the fragment Caddy reads; that
  # is no reason to expose it to everyone.
  ssh "$SITESOLIDE_SERVER" "sudo install -m 600 -o $DEPLOY_USER -g $DEPLOY_USER $WORK_VM/codes.json $CODES_FILE"
}

# --- door page --------------------------------------------------------------

# Every URL of the locked host is rewritten towards this file: if it is missing,
# the lock answers 404 instead of 401. A site may have its own in
# <slug>/verrou.html of its folder; otherwise it is generated here.
#
# GENERATED RATHER THAN VERSIONED: its footer carries the address to ask a code
# from, SITESOLIDE_CONTACT of the configuration. A committed file would freeze
# it to the software author's, and the visitor of a preview would write to a
# stranger.
deposit_door_page() {
  local source="${SITE_FOLDER:-${SITESOLIDE_SITES_REPO:-}/$SLUG}/verrou.html"
  if [ ! -f "$source" ]; then
    source="$WORK/verrou.html"
    SITESOLIDE_CONTACT="${SITESOLIDE_CONTACT:-}" bun "$REPO_ROOT/portal/scripts/lock-page.ts" "$source" >/dev/null
  fi

  echo "-> door page"
  ssh "$SITESOLIDE_SERVER" "sudo mkdir -p $DOOR_PAGES_DIR/$SLUG && sudo chown $DEPLOY_USER:$DEPLOY_USER $DOOR_PAGES_DIR/$SLUG"
  rsync -a "$source" "$SITESOLIDE_SERVER:$DOOR_PAGES_DIR/$SLUG/index.html"
  # Caddy runs under its own user: without these permissions, the door page
  # exists but stays unreadable, and the lock answers 403.
  ssh "$SITESOLIDE_SERVER" "sudo chmod 755 $DOOR_PAGES_DIR $DOOR_PAGES_DIR/$SLUG && sudo chmod 644 $DOOR_PAGES_DIR/$SLUG/index.html"
}

# --- Caddy fragment ----------------------------------------------------------

# Deposit, validate, reload, and restore if either of the two fails. Production
# must never stay broken, not even for a second: it is the same ritual as
# bin/generate-domains.sh.
#
# The fragment keeps the name the machine carries, verrous.caddy: the Caddyfile
# imports the folder by glob, so a new name would install a second file next to
# the one in service, and every locked site would carry two stanzas.
install_fragment() {
  echo "-> generating the fragment"
  ssh "$SITESOLIDE_SERVER" "SITES_DIR=$SITES_DIR CODES_FILE=$CODES_FILE DOOR_PAGES_DIR=$DOOR_PAGES_DIR SITESOLIDE_ZONE=$SITESOLIDE_ZONE /usr/local/bin/bun run /srv/api/current/scripts/generate-locks.ts" > "$WORK/verrous.caddy"

  # The generator exits in error as soon as a site asks for a lock without a
  # valid code, or a code stays in force on a site its manifest says is open:
  # nothing is installed, nobody wrongly believes his site closed.
  # The trailing space is not decorative: it is what tells the stanza header
  # "# Preview lock: <slug>" from the header's own line "# Preview locks: ...".
  echo "   stanzas: $(grep -c '^# Preview lock: ' "$WORK/verrous.caddy" || true)"

  open_work_vm
  rsync -a "$WORK/verrous.caddy" "$SITESOLIDE_SERVER:$WORK_VM/verrous.caddy"
  ssh "$SITESOLIDE_SERVER" "
    set -e
    sudo mkdir -p $LOCKS_DIR

    # Telling 'there was no fragment' from 'the backup failed' is not a
    # stylistic scruple. Confusing the two DELETES the fragment in service while
    # believing it rolls back: Caddy is still running on its configuration in
    # memory, nobody sees anything, and the next reload reopens every locked
    # site. No '|| true' here: a backup that is impossible stops the gesture, it
    # does not authorise it blindly.
    BEFORE=no
    if sudo test -e $LOCKS_DIR/verrous.caddy; then
      sudo cp $LOCKS_DIR/verrous.caddy $WORK_VM/verrous.caddy.before
      BEFORE=yes
    fi

    restore() {
      if [ \"\$BEFORE\" = yes ]; then
        sudo install -m 644 -o root -g root $WORK_VM/verrous.caddy.before $LOCKS_DIR/verrous.caddy
      else
        sudo rm -f $LOCKS_DIR/verrous.caddy
      fi
    }

    sudo install -m 644 -o root -g root $WORK_VM/verrous.caddy $LOCKS_DIR/verrous.caddy

    # caddy validate launched by hand does not load /etc/caddy/cloudflare.env,
    # which systemd injects through EnvironmentFile: without the token, the DNS
    # module refuses the configuration and the failure would say nothing about
    # the Caddyfile.
    if ! sudo bash -c 'set -a; . /etc/caddy/cloudflare.env; set +a; caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile' >/dev/null 2>&1; then
      restore
      echo 'invalid configuration, previous fragment restored, Caddy never reloaded' >&2
      exit 1
    fi

    # The reload is inside the same safety net as the validation, and not after
    # it. A fragment left on disk without ever having been loaded cuts nothing
    # at the time: Caddy carries on with its configuration in memory, and a
    # refused reload never replaces the one in service. The danger is deferred.
    # At the machine's next boot, or at the next 'systemctl restart caddy', that
    # is the file Caddy reads; if it refuses it, Caddy does not start AT ALL,
    # the landing included, and with no operator in front of the screen. The gap
    # between validate and a real load is narrow, it is not nil: validate binds
    # to no port and does not touch the TLS storage.
    if ! sudo systemctl reload caddy; then
      restore
      sudo systemctl reload caddy || true
      echo 'reload refused, previous fragment restored' >&2
      exit 1
    fi
  "
  echo "-> Caddy reloaded"
}

# --- real verification -------------------------------------------------------

http_code() {
  curl -s -o /dev/null -w '%{http_code}' --max-time 15 "https://${1:-$HOST}/"
}

# The cookie goes through the configuration read on standard input, never
# through an argument: curl -K - accepts the same options as on the command line
# without exposing them in the process list.
http_code_with_cookie() {
  local host="${2:-$HOST}" name="${3:-$SLUG}"
  curl -s -o /dev/null -w '%{http_code}' --max-time 15 -K - <<EOF
url = "https://$host/"
header = "Cookie: lock_$name=$1"
EOF
}

expect_code() {
  local expected="$1" got="$2" what="$3"
  if [ "$got" != "$expected" ]; then
    echo "   FAILED: $what expected $expected, got $got" >&2
    return 1
  fi
  echo "   ok: $what -> $got"
}

verify_closed() {
  local value="$1" failures=0
  echo "-> verification on https://$HOST/"
  # Caddy's reload is asynchronous: the first request may still leave into the
  # old configuration.
  sleep 2
  expect_code 401 "$(http_code)" "without a code" || failures=1
  expect_code 200 "$(http_code_with_cookie "$value")" "with the right code" || failures=1
  [ "$failures" -eq 0 ] || { echo "the lock is not in the expected state" >&2; exit 1; }
}

verify_open() {
  echo "-> verification on https://$HOST/"
  sleep 2
  expect_code 200 "$(http_code)" "without a code" || { echo "the preview is not reopened" >&2; exit 1; }
}

# Called from the exit trap, and from it alone. Announcing at the end of the
# nominal path was a trap: between the setting of the code and that end there is
# a reload, a wait and two requests towards production. Anything that fails
# there -- DNS not propagated yet, wifi cut, a reload slower than the wait --
# left a lock IN SERVICE with a code nobody had seen, and "bin/lock.sh code" to
# get out of it failed at exactly the same place. The code therefore comes out
# whatever happens.
announce() {
  local value="$1" status="${2:-0}" recall="${3:-no}"
  if [ "$status" != 0 ]; then
    cat <<EOF

   WARNING: the gesture was interrupted (exit $status), and the lock's state is
   not the one this script usually guarantees.

   The code below is the one this gesture generated. If it was set, it is now
   the only one that opens the preview: note it down BEFORE anything else, then
   read the real state again with "bin/lock.sh state $SLUG".
EOF
  elif [ "$recall" = yes ]; then
    cat <<EOF

   Preview already closed. Neither the code, nor the fragment, nor the manifest
   has changed; only the door page was deposited again, to follow the
   repository's template. The code below is the one in force.
EOF
  else
    cat <<EOF

   Preview closed.
EOF
  fi
  cat <<EOF

   Code   : $value
   Link   : https://$HOST/?key=$value

   This link sets a cookie valid for thirty days, then sends back to the home
   page. The code is not a secret: it travels in the clear in the URL and lives
   in the clear in Caddy's configuration. It keeps out a passing visitor, not
   an adversary.
EOF
}

# --- subcommands -------------------------------------------------------------

SUBCOMMAND="${1:-}"
SLUG="${2:-}"

case "$SUBCOMMAND" in
  enable)
    require_site
    take_caddy_lock
    require_portal_agreed lock

    # Running "enable" again on a site already closed generated a fresh code,
    # and therefore broke the link already sent to the client. It is the most
    # natural gesture to find a lost code again: it returns it, without changing
    # anything. Renewal stays a distinct gesture, "code", which one does not do
    # by mistake.
    ALREADY="$(code_in_force)"
    if [ "$LOCKED" = "true" ] && [ -n "$ALREADY" ]; then
      # The door page, for its part, follows the repository's template:
      # depositing it again changes neither the code nor the access, and that is
      # how a touch-up of portal/src/page.ts reaches a site already closed.
      # Before naming the code: a failure here has set nothing, and the
      # interruption notice would say the contrary.
      deposit_door_page
      CODE="$ALREADY"
      announce "$CODE" 0 yes
      ANNOUNCED=yes
      exit 0
    fi

    require_preview_only
    require_import
    CODE="$(generate_code)"
    write_lock "$MANIFEST" true
    set_code "$CODE"
    deposit_door_page
    install_fragment
    # Caddy is reloaded: the verification no longer needs the lock, and its two
    # seconds of waiting have no reason to keep the gatekeeper waiting.
    release_caddy_lock
    verify_closed "$CODE"
    announce "$CODE"
    ANNOUNCED=yes
    echo "   Remember to commit $SLUG/sitesolide.json in the sites repository:"
    echo "   without that commit, a later deployment would read a manifest"
    echo "   without a lock there and would reopen the preview."
    ;;

  code)
    require_site
    [ "$LOCKED" = "true" ] || {
      echo "$SLUG is not locked: bin/lock.sh enable $SLUG" >&2
      exit 1
    }
    # The code touches neither the manifest nor the site's block, but it reloads
    # Caddy and restores if need be: it must not do so in the middle of a
    # gatekeeper transaction, which would validate or probe something other than
    # what it believes.
    take_caddy_lock
    PREVIOUS="$(code_in_force)"
    CODE="$(generate_code)"
    set_code "$CODE"
    deposit_door_page
    install_fragment
    release_caddy_lock
    verify_closed "$CODE"
    # The old code must have stopped working, otherwise the replacement has
    # replaced nothing and the link already circulated still opens the site.
    if [ -n "$PREVIOUS" ]; then
      expect_code 401 "$(http_code_with_cookie "$PREVIOUS")" "with the old code" || exit 1
    fi
    announce "$CODE"
    ANNOUNCED=yes
    ;;

  disable)
    require_site
    take_caddy_lock
    require_portal_agreed unlock
    # The order matters: the manifest first, the code next. Removing the code
    # while leaving "lock": true would make the generation fail, and the site
    # would stay closed with a lost code.
    write_lock "$MANIFEST" false
    set_code ""
    install_fragment
    release_caddy_lock
    verify_open
    echo
    echo "   Preview reopened. Remember to commit $SLUG/sitesolide.json."
    ;;

  state)
    # Columns that may diverge, and that is the whole point: the descriptor says
    # what is wanted, the fragment what is installed, the HTTP codes what the
    # visitor really gets.
    #
    # WITH CODE is measured with the code read IN the fragment in service, and
    # not with the one the operator believes he holds. An INSTALLED column at
    # "yes" only says that a stanza is present: a fragment carrying a stale code
    # shows a perfectly reassuring 401 while the link already sent to the client
    # no longer opens anything.
    #
    # FINAL DOMAIN recalls that the lock only closes the preview. An active final
    # domain serves the same site without a code: the line measures it too,
    # otherwise a 401 on the preview would let one believe the site closed.
    FILTER="$SLUG"
    printf '%-22s %-7s %-9s %-10s %-10s %s\n' \
      "SITE" "WANTED" "INSTALLED" "NO CODE" "WITH CODE" "FINAL DOMAIN"
    FRAGMENT="$(ssh "$SITESOLIDE_SERVER" "sudo cat $LOCKS_DIR/verrous.caddy 2>/dev/null || true")"

    # One "slug|folder" pair per line, because the two do not always coincide:
    # "sitesolide lock --status" sets SITESOLIDE_PROJECT_DIR, and the project
    # may live outside the sites repository, in a folder that does not carry its
    # slug.
    PAIRS=()
    if [ -n "${SITESOLIDE_PROJECT_DIR:-}" ]; then
      PAIRS=("$FILTER|${SITESOLIDE_PROJECT_DIR%/}")
    else
      for folder in "${SITESOLIDE_SITES_REPO:-}"/*/; do
        PAIRS+=("$(basename "$folder")|${folder%/}")
      done
    fi

    for pair in "${PAIRS[@]}"; do
      name="${pair%%|*}"
      folder="${pair#*|}/"
      [ -z "$FILTER" ] || [ "$FILTER" = "$name" ] || continue

      # The landing has neither a preview nor a manifest. Without this skip, the
      # table shows for it a line WANTED=false, FINAL DOMAIN=- and a 404 on
      # landing.$SITESOLIDE_ZONE: a state table that lies is exactly what this
      # subcommand exists to avoid.
      [ "$name" = landing ] && continue

      HOST="$name.$SITESOLIDE_ZONE"
      # An unreadable manifest stops the table rather than removing its line: a
      # mute WANTED column on a locked site would read as an open site.
      fields="$(manifest_fields "${folder}sitesolide.json")"
      { read -r wanted; read -r domain; read -r active; } <<<"$fields"
      installed=no
      with_code="-"
      if printf '%s\n' "$FRAGMENT" | grep -q "^# Preview lock: $name\$"; then
        installed=yes
        installed_code="$(printf '%s\n' "$FRAGMENT" | grep -o "@lock_key_$name query key=[A-Z0-9]*" | head -1 | sed 's/.*key=//')"
        # The host AND the site's name are passed explicitly. Without them, the
        # function falls back on $HOST and $SLUG, and $SLUG is empty as soon as
        # "state" runs without a filter: the cookie was then called "lock_",
        # Caddy returned 401, and the column showed for each locked site a code
        # that no longer opens anything. A state table that lies is exactly what
        # this subcommand exists to avoid.
        [ -z "$installed_code" ] || with_code="$(http_code_with_cookie "$installed_code" "$HOST" "$name")"
      fi

      if [ -z "$domain" ]; then
        column="-"
      elif [ "$active" = "true" ]; then
        column="$domain $(http_code "$domain") (active, outside the lock)"
      else
        column="$domain (inactive)"
      fi

      printf '%-22s %-7s %-9s %-10s %-10s %s\n' \
        "$name" "$wanted" "$installed" "$(http_code)" "$with_code" "$column"
    done
    ;;

  *)
    usage
    ;;
esac
