/**
 * Compare a deployment file to what the manifest would generate.
 *
 * **The comparison is about directives, never about text.** Hand-written files
 * carry comments that are the memory of real outages, such as the reason a
 * fragment uses no `handle`, and replacing them with the generated version
 * would erase the explanation without changing the service at all. A `deploy`
 * that stopped on that difference would cost a minute for nothing, and
 * overwriting it would cost the reason.
 *
 * Order is set aside along with comments: systemd does not read the order of
 * a section's lines, and Caddy sorts a block's directives itself. **Except
 * inside a `route`**, the one Caddy directive that keeps the written order,
 * and the reason the generator writes one: a protected block takes the
 * visitor's identity headers off before `forward_auth` copies the portal's on
 * (bin/cli/portal.ts). There, the same lines in another order are another
 * block: an `import <slug>-routes` moved inside the route ahead of
 * `forward_auth` would serve the site before the portal is asked. A `route`
 * therefore compares as one directive, its lines in their order, nested
 * blocks included.
 *
 * Pure: reads two texts, returns a comparison.
 */

/** The lines that decide: neither blank, nor comments, without indentation. */
export function usefulDirectives(text: string): string[] {
  return text
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith("#"));
}

export type Divergence = {
  /** Present in the file in place, absent from what the manifest generates. */
  lost: string[];
  /** Generated by the manifest, absent from the file in place. */
  added: string[];
};

/** A `route` opening, with or without a matcher: `route {`, `route /api/* {`. */
const ROUTE_OPENING = /^route(\s.*)?\{$/;

function braces(line: string): number {
  return (line.match(/\{/g) ?? []).length - (line.match(/\}/g) ?? []).length;
}

/**
 * What one directive is, for the comparison: `key` decides, `text` is what a
 * refusal shows. A line outside any route is both. A whole route is one
 * directive, its lines kept in order: `key` holds them as a JSON array, which no
 * line can forge by carrying a separator, and `text` writes them on one line.
 */
type Directive = { key: string; text: string };

function directives(text: string): Directive[] {
  const lines = usefulDirectives(text);
  const result: Directive[] = [];
  for (let i = 0; i < lines.length; i++) {
    if (!ROUTE_OPENING.test(lines[i]!)) {
      result.push({ key: lines[i]!, text: lines[i]! });
      continue;
    }
    const group: string[] = [];
    let depth = 0;
    for (; i < lines.length; i++) {
      group.push(lines[i]!);
      depth += braces(lines[i]!);
      if (depth <= 0) break;
    }
    const shown = group.reduce((joined, line, n) => {
      if (n === 0) return line;
      return `${joined}${group[n - 1]!.endsWith("{") || line === "}" ? " " : "; "}${line}`;
    }, "");
    result.push({ key: JSON.stringify(group), text: shown });
  }
  return result;
}

export function compareDirectives(current: string, generated: string): Divergence {
  const a = directives(current);
  const g = directives(generated);
  const inA = new Set(a.map((directive) => directive.key));
  const inG = new Set(g.map((directive) => directive.key));
  return {
    lost: a.filter((directive) => !inG.has(directive.key)).map((directive) => directive.text),
    added: g.filter((directive) => !inA.has(directive.key)).map((directive) => directive.text),
  };
}

export function sameDirectives(current: string, generated: string): boolean {
  const { lost, added } = compareDirectives(current, generated);
  return lost.length === 0 && added.length === 0;
}

/**
 * Enough to name the divergence in a refusal, without drowning the message. The
 * total count is stated before the cut: knowing that twelve lines are not shown
 * changes what you go and read next.
 */
export function summariseDivergence(divergence: Divergence, limit = 4): string[] {
  const { lost, added } = divergence;
  const lines: string[] = [];
  for (const [sign, group] of [
    ["-", lost],
    ["+", added],
  ] as const) {
    for (const line of group.slice(0, limit)) lines.push(`  ${sign} ${line}`);
    if (group.length > limit) {
      lines.push(`  ${sign} ... and ${group.length - limit} more`);
    }
  }
  return lines;
}

/**
 * How many entries an rsync run with `--dry-run --itemize-changes` would send
 * or delete, read from what it lists: one line per entry, its first character
 * saying what would happen. `<` and `>` a file sent, `c` an entry created
 * there, `h` a hard link, `*deleting` an entry removed. A line opening with a
 * dot is an entry whose time, mode or owner alone differs: not a change of
 * what is served, the modes being set again on the machine after every send
 * (sentModesCommand in bin/sitesolide.ts). Read on GNU rsync 3 and on the
 * openrsync macOS ships, which word their lines alike.
 */
export function countItemized(output: string): number {
  return output.split("\n").filter((line) => /^(\*deleting\s|[<>ch][fdLDS])/.test(line)).length;
}
