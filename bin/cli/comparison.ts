/**
 * Compare a deployment file to what the manifest would generate.
 *
 * **The comparison is about directives, never about text.** Hand-written files
 * carry comments that are the memory of real outages, such as the reason a
 * fragment uses no `handle`, and replacing them with the generated version
 * would erase the explanation without changing the service at all. A `deploy`
 * that stopped on that difference would cost a minute for nothing, and
 * overwriting it would cost the reason.
 *
 * Order is set aside along with comments: systemd does not read the latter, and
 * Caddy sorts its own directives. The limit is known and worth stating: inside
 * a `route` block Caddy follows the written order, and two files with the same
 * lines in a different order would not be equivalent there. The generator does
 * not use `route`, it places matchers, precisely because an exclusive group
 * would break the preview lock.
 *
 * Pure: reads two texts, returns a comparison.
 */

/** The lines that decide: neither blank, nor comments, without indentation. */
export function usefulDirectives(text: string): string[] {
  return text
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith("#"));
}

export type Divergence = {
  /** Present in the file in place, absent from what the manifest generates. */
  lost: string[];
  /** Generated by the manifest, absent from the file in place. */
  added: string[];
};

export function compareDirectives(current: string, generated: string): Divergence {
  const a = usefulDirectives(current);
  const g = usefulDirectives(generated);
  return {
    lost: a.filter((line) => !g.includes(line)),
    added: g.filter((line) => !a.includes(line)),
  };
}

export function sameDirectives(current: string, generated: string): boolean {
  const { lost, added } = compareDirectives(current, generated);
  return lost.length === 0 && added.length === 0;
}

/**
 * Enough to name the divergence in a refusal, without drowning the message. The
 * total count is stated before the cut: knowing that twelve lines are not shown
 * changes what you go and read next.
 */
export function summariseDivergence(divergence: Divergence, limit = 4): string[] {
  const { lost, added } = divergence;
  const lines: string[] = [];
  for (const [sign, group] of [
    ["-", lost],
    ["+", added],
  ] as const) {
    for (const line of group.slice(0, limit)) lines.push(`  ${sign} ${line}`);
    if (group.length > limit) {
      lines.push(`  ${sign} ... and ${group.length - limit} more`);
    }
  }
  return lines;
}
